        /// <summary>
        /// TC7: Repository saves and retrieves entity.
        /// </summary>
        [TestMethod]
        public void TestRepository_SaveAndRetrieve()
        {
            var entity = new QuantityMeasurementEntity(
                "1 FEET",
                QuantityMeasurementEntity.Operations.CONVERT,
                "12.00 INCHES"
            );

            _repository.Save(entity);
            var all = _repository.GetAllMeasurements();

            Assert.AreEqual(1,         all.Count);
            Assert.AreEqual(entity.Id, all[0].Id);
        }

        /// <summary>
        /// TC8: Repository FindById returns correct entity.
        /// </summary>
        [TestMethod]
        public void TestRepository_FindById()
        {
            var entity = new QuantityMeasurementEntity(
                "1 FEET",
                QuantityMeasurementEntity.Operations.CONVERT,
                "12.00 INCHES"
            );
            _repository.Save(entity);

            var found = _repository.FindById(entity.Id);

            Assert.IsNotNull(found);
            Assert.AreEqual(entity.Id, found!.Id);
        }

        /// <summary>
        /// TC9: Repository DeleteById removes entity.
        /// </summary>
        [TestMethod]
        public void TestRepository_DeleteById()
        {
            var entity = new QuantityMeasurementEntity(
                "1 FEET",
                QuantityMeasurementEntity.Operations.CONVERT,
                "12.00 INCHES"
            );
            _repository.Save(entity);

            _repository.DeleteById(entity.Id);

            Assert.AreEqual(0, _repository.GetAllMeasurements().Count);
        }

        /// <summary>
        /// TC10: Repository ClearAll removes all entities.
        /// </summary>
        [TestMethod]
        public void TestRepository_ClearAll()
        {
            _repository.Save(new QuantityMeasurementEntity(
                "1 FEET",
                QuantityMeasurementEntity.Operations.CONVERT,
                "12.00 INCHES"
            ));
            _repository.Save(new QuantityMeasurementEntity(
                "1 KG",
                QuantityMeasurementEntity.Operations.CONVERT,
                "1000.00 GRAM"
            ));

            _repository.ClearAll();

            Assert.AreEqual(0, _repository.GetAllMeasurements().Count);
        }

