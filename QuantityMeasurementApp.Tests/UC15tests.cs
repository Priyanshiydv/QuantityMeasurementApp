        /// <summary>
        /// TC1: Single operand entity construction.
        /// </summary>
        [TestMethod]
        public void TestEntity_SingleOperandConstruction()
        {
            var entity = new QuantityMeasurementEntity(
                "1 FEET",
                QuantityMeasurementEntity.Operations.CONVERT,
                "12.00 INCHES"
            );

            Assert.AreEqual("1 FEET",   entity.FirstOperand);
            Assert.AreEqual(QuantityMeasurementEntity.Operations.CONVERT,
                            entity.OperationType);
            Assert.AreEqual("12.00 INCHES", entity.Result);
            Assert.IsFalse(entity.HasError);
        }

        /// <summary>
        /// TC2: Binary operand entity construction.
        /// </summary>
        [TestMethod]
        public void TestEntity_BinaryOperandConstruction()
        {
            var entity = new QuantityMeasurementEntity(
                "1 FEET",
                "12 INCHES",
                QuantityMeasurementEntity.Operations.ADD,
                "2.00 FEET",
                "LENGTH"
            );

            Assert.AreEqual("1 FEET",    entity.FirstOperand);
            Assert.AreEqual("12 INCHES", entity.SecondOperand);
            Assert.AreEqual(QuantityMeasurementEntity.Operations.ADD,
                            entity.OperationType);
            Assert.AreEqual("2.00 FEET", entity.Result);
            Assert.IsFalse(entity.HasError);
        }

        /// <summary>
        /// TC3: Error entity construction.
        /// </summary>
        [TestMethod]
        public void TestEntity_ErrorConstruction()
        {
            var entity = new QuantityMeasurementEntity(
